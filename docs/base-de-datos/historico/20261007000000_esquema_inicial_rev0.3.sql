CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.usuario_tiene_rol(nombre_rol text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfil_roles pr
    JOIN public.roles r ON r.id = pr.rol_id
    WHERE pr.perfil_id = auth.uid()
      AND r.nombre = nombre_rol
  );
$$;

CREATE OR REPLACE FUNCTION public.registrar_transicion_partido()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.estado IS DISTINCT FROM OLD.estado THEN
    INSERT INTO public.partido_estados_historial (
      partido_id, estado_anterior, estado_nuevo, usuario_id, motivo
    )
    VALUES (
      NEW.id,
      OLD.estado,
      NEW.estado,
      COALESCE(NEW.updated_by, auth.uid()),
      COALESCE(NEW.motivo_estado, 'Transición de estado')
    );
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.historial_resultado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  siguiente_version integer;
BEGIN
  SELECT COALESCE(MAX(version), 0) + 1
    INTO siguiente_version
  FROM public.resultados_historial
  WHERE resultado_id = OLD.id;

  INSERT INTO public.resultados_historial (
    resultado_id, partido_id, version, goles_local, goles_visitante,
    estado, es_oficial, validado_por, validado_at, observaciones,
    reemplazado_por
  )
  VALUES (
    OLD.id, OLD.partido_id, siguiente_version, OLD.goles_local,
    OLD.goles_visitante, OLD.estado, OLD.es_oficial, OLD.validado_por,
    OLD.validado_at, OLD.observaciones, auth.uid()
  );

  RETURN NEW;
END;
$$;

-- Valida los conflictos duros explícitos del ERS:
-- 1) un equipo no puede estar en dos partidos solapados;
-- 2) una cancha no puede estar ocupada por dos partidos solapados;
-- 3) una cancha bloqueada no puede utilizarse.
CREATE OR REPLACE FUNCTION public.validar_conflictos_partido()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  nuevo_periodo tstzrange := tstzrange(NEW.inicio_programado, NEW.fin_programado, '[)');
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.partidos p
    WHERE p.id <> NEW.id
      AND (p.equipo_local_id IN (NEW.equipo_local_id, NEW.equipo_visitante_id)
           OR p.equipo_visitante_id IN (NEW.equipo_local_id, NEW.equipo_visitante_id))
      AND tstzrange(p.inicio_programado, p.fin_programado, '[)') && nuevo_periodo
      AND p.estado NOT IN ('CANCELADO','NO_PROGRAMADO')
  ) THEN
    RAISE EXCEPTION 'Conflicto de programación: un equipo ya tiene un partido en ese intervalo';
  END IF;

  IF NEW.cancha_id IS NOT NULL AND EXISTS (
    SELECT 1
    FROM public.partidos p
    WHERE p.id <> NEW.id
      AND p.cancha_id = NEW.cancha_id
      AND tstzrange(p.inicio_programado, p.fin_programado, '[)') && nuevo_periodo
      AND p.estado NOT IN ('CANCELADO','NO_PROGRAMADO')
  ) THEN
    RAISE EXCEPTION 'Conflicto de programación: la cancha ya está ocupada en ese intervalo';
  END IF;

  IF NEW.cancha_id IS NOT NULL AND EXISTS (
    SELECT 1
    FROM public.disponibilidad_canchas d
    WHERE d.cancha_id = NEW.cancha_id
      AND d.tipo = 'BLOQUEADA'
      AND d.periodo && nuevo_periodo
  ) THEN
    RAISE EXCEPTION 'Conflicto de programación: la cancha no está disponible en ese intervalo';
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.calcular_tabla(p_grupo_id uuid)
RETURNS TABLE (
  equipo_id uuid,
  equipo text,
  pj bigint,
  pg bigint,
  pe bigint,
  pp bigint,
  gf bigint,
  gc bigint,
  dg bigint,
  puntos bigint,
  posicion bigint
)
LANGUAGE sql
STABLE
AS $$
  WITH resultados_validos AS (
    SELECT
      p.equipo_local_id,
      p.equipo_visitante_id,
      r.goles_local,
      r.goles_visitante,
      t.puntos_victoria,
      t.puntos_empate,
      t.puntos_derrota
    FROM public.partidos p
    JOIN public.jornadas j ON j.id = p.jornada_id
    JOIN public.resultados r ON r.partido_id = p.id
    JOIN public.grupos g ON g.id = j.grupo_id
    JOIN public.categorias c ON c.id = g.categoria_id
    JOIN public.temporadas t ON t.id = c.temporada_id
    WHERE j.grupo_id = p_grupo_id
      AND r.es_oficial = true
      AND p.estado IN ('FINALIZADO','RESUELTO_ADMINISTRATIVAMENTE')
  ),
  equipos_grupo AS (
    SELECT e.id, e.nombre
    FROM public.equipos e
    WHERE e.grupo_id = p_grupo_id
  ),
  estadisticas AS (
    SELECT
      e.id AS equipo_id,
      e.nombre AS equipo,
      COUNT(v.*) FILTER (
        WHERE v.equipo_local_id = e.id OR v.equipo_visitante_id = e.id
      ) AS pj,
      COUNT(v.*) FILTER (
        WHERE (v.equipo_local_id = e.id AND v.goles_local > v.goles_visitante)
           OR (v.equipo_visitante_id = e.id AND v.goles_visitante > v.goles_local)
      ) AS pg,
      COUNT(v.*) FILTER (
        WHERE (v.equipo_local_id = e.id OR v.equipo_visitante_id = e.id)
          AND v.goles_local = v.goles_visitante
      ) AS pe,
      COUNT(v.*) FILTER (
        WHERE (v.equipo_local_id = e.id AND v.goles_local < v.goles_visitante)
           OR (v.equipo_visitante_id = e.id AND v.goles_visitante < v.goles_local)
      ) AS pp,
      COALESCE(SUM(
        CASE
          WHEN v.equipo_local_id = e.id THEN v.goles_local
          WHEN v.equipo_visitante_id = e.id THEN v.goles_visitante
        END
      ),0) AS gf,
      COALESCE(SUM(
        CASE
          WHEN v.equipo_local_id = e.id THEN v.goles_visitante
          WHEN v.equipo_visitante_id = e.id THEN v.goles_local
        END
      ),0) AS gc,
      COALESCE(SUM(
        CASE
          WHEN v.goles_local = v.goles_visitante THEN v.puntos_empate
          WHEN (v.equipo_local_id = e.id AND v.goles_local > v.goles_visitante)
            OR (v.equipo_visitante_id = e.id AND v.goles_visitante > v.goles_local)
            THEN v.puntos_victoria
          ELSE v.puntos_derrota
        END
      ),0) AS puntos
    FROM equipos_grupo e
    LEFT JOIN resultados_validos v
      ON v.equipo_local_id = e.id OR v.equipo_visitante_id = e.id
    GROUP BY e.id, e.nombre
  )
  SELECT
    equipo_id, equipo, pj, pg, pe, pp, gf, gc, gf-gc AS dg, puntos,
    RANK() OVER (ORDER BY puntos DESC, (gf-gc) DESC, gf DESC, equipo) AS posicion
  FROM estadisticas
  ORDER BY posicion, equipo;
$$;

