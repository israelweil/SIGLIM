CREATE OR REPLACE FUNCTION public.consultar_programacion_publica(
  p_desde timestamptz,
  p_hasta timestamptz
)
RETURNS TABLE (
  jornada_id uuid,
  partido_id uuid,
  inicio_programado timestamptz,
  equipo_local text,
  equipo_visitante text,
  cancha text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    j.id,
    p.id,
    p.inicio_programado,
    el.nombre,
    ev.nombre,
    c.nombre
  FROM public.jornadas j
  JOIN public.partidos p ON p.jornada_id = j.id
  JOIN public.equipos el ON el.id = p.equipo_local_id
  JOIN public.equipos ev ON ev.id = p.equipo_visitante_id
  LEFT JOIN public.canchas c ON c.id = p.cancha_id
  WHERE j.estado_publicacion = 'PUBLICADO'
    AND p.inicio_programado >= p_desde
    AND p.inicio_programado < p_hasta
  ORDER BY p.inicio_programado;
$$;

CREATE OR REPLACE FUNCTION public.consultar_resultados_publicos(
  p_desde timestamptz,
  p_hasta timestamptz
)
RETURNS TABLE (
  partido_id uuid,
  inicio_programado timestamptz,
  equipo_local text,
  equipo_visitante text,
  goles_local integer,
  goles_visitante integer
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    p.id,
    p.inicio_programado,
    el.nombre,
    ev.nombre,
    r.goles_local,
    r.goles_visitante
  FROM public.resultados r
  JOIN public.partidos p ON p.id = r.partido_id
  JOIN public.jornadas j ON j.id = p.jornada_id
  JOIN public.equipos el ON el.id = p.equipo_local_id
  JOIN public.equipos ev ON ev.id = p.equipo_visitante_id
  WHERE r.es_oficial = true
    AND j.estado_publicacion = 'PUBLICADO'
    AND p.inicio_programado >= p_desde
    AND p.inicio_programado < p_hasta
  ORDER BY p.inicio_programado DESC;
$$;

CREATE OR REPLACE FUNCTION public.consultar_tabla_publica(
  p_grupo_id uuid
)
RETURNS TABLE (
  equipo_id uuid,
  equipo text,
  pj bigint,
  pg bigint,
  pe bigint,
  pp bigint,
  gf bigint,
  gc bigint,
  dg bigint,
  puntos bigint,
  posicion bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT t.*
  FROM public.calcular_tabla(p_grupo_id) t
  WHERE EXISTS (
    SELECT 1
    FROM public.jornadas j
    WHERE j.grupo_id = p_grupo_id
      AND j.estado_publicacion = 'PUBLICADO'
  );
$$;

