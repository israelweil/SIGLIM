  rol_id bigint NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
  permiso_id bigint NOT NULL REFERENCES public.permisos(id) ON DELETE CASCADE,
  PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE public.temporadas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre varchar(100) NOT NULL,
  fecha_inicio date NOT NULL,
  fecha_fin date,
  estado public.estado_temporada NOT NULL DEFAULT 'CONFIGURACION',
  reglas_version varchar(100),
  reglas_referencia text,
  puntos_victoria integer,
  puntos_empate integer,
  puntos_derrota integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_temporada_fechas
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
  CONSTRAINT ck_temporada_puntos
    CHECK (
      puntos_victoria IS NULL AND puntos_empate IS NULL AND puntos_derrota IS NULL
      OR puntos_victoria >= 0 AND puntos_empate >= 0 AND puntos_derrota >= 0
